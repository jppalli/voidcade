// Writes the brief for the art team. Run: npm run art:spec
//   art/ART_BRIEF.md     the whole brief: the game, the style, the rules and the list of every picture
//   art/art-slots.csv    the same list as a table (for a spreadsheet)
// The numbers come from src/artslots.ts, so the brief never disagrees with the game.
import fs from 'node:fs';
import path from 'node:path';
import { DIRS, ROOT, loadSlots } from './art-lib.mjs';

const { spec, slots } = await loadSlots();
let delivered = {};
try { delivered = JSON.parse(fs.readFileSync(DIRS.manifest, 'utf8')).files ?? {}; } catch { /* no manifest yet */ }
const key = s => `${s.folder}/${s.id}`;
const isDone = s => !!delivered[key(s)];
const ext = s => delivered[key(s)]?.ext;

// How big each prop is shown in the map, from worldmap.ts.
const shown = {};
try {
  const map = fs.readFileSync(path.join(ROOT, 'src', 'worldmap.ts'), 'utf8');
  for (const m of map.matchAll(/svg:\s*P\.(\w+)(?:\([^)]*\))?,\s*size:\s*(\d+)/g)) (shown[m[1].toLowerCase()] ??= []).push(Number(m[2]));
} catch { /* the note is just left out */ }
const shownText = s => {
  const v = shown[s.id];
  return v ? `Shown about ${Math.min(...v)}${Math.max(...v) !== Math.min(...v) ? ' to ' + Math.max(...v) : ''} px wide in the map` : '';
};

const kits = [];
for (const s of slots) {
  let k = kits.find(x => x.name === s.kit);
  if (!k) kits.push((k = { name: s.kit, gate: s.gate, folder: s.folder, kind: s.kind, slots: [] }));
  k.slots.push(s);
}
const have = slots.filter(isDone).length;
const count = f => slots.filter(s => s.folder === f).length;
const I = spec.item, IC = spec.icon, PR = spec.prop;
const pct = n => Math.round(n * 100);
const kb = spec.maxBytes / 1000;
const sizeText = s => `${s.w} x ${s.h}`;

const sections = kits.map(k => {
  const first = k.slots[0];
  const head = k.kind === 'icon'
    ? `Delivered **all together**: the game keeps its own icons until every icon of this kit is here, so the buttons never mix two styles.`
    : k.kind === 'prop'
      ? `Delivered **world by world**: the game keeps its own scenery for this world until every picture of this kit is here.`
      : k.kind === 'decoy'
        ? 'Used one by one.'
        : 'Used one by one: each picture replaces the game\'s own as soon as it is delivered.';
  const rows = k.slots.map(s => {
    const note = s.kind === 'prop' ? [shownText(s), s.id === 'butterfly' ? 'Wings open and flat; the game flaps them' : ''].filter(Boolean).join('. ') : s.kind === 'icon' ? s.use : s.kind === 'decoy' ? s.use : '';
    const st = isDone(s) ? `delivered (${ext(s)})` : 'missing';
    const formats = s.formats.map(f => f.toUpperCase()).join(' or ');
    return `| \`${s.folder}/${s.id}\` | ${s.name} | ${s.rarity ?? '-'} | ${formats} | ${s.kind === 'item' || s.kind === 'decoy' ? sizeText(s) : `${sizeText(s)} px, or viewBox ${s.box[0]} x ${s.box[1]}`} | ${note || '-'} | ${st} |`;
  }).join('\n');
  return `### ${k.name}\n\n${head} (${k.slots.filter(isDone).length} of ${k.slots.length} delivered)\n\n| File (without extension) | Name | Rarity | Format | Size | Notes | Status |\n|---|---|---|---|---|---|---|\n${rows}\n`;
}).join('\n');

const md = `# Needle in a Haystack: art brief

Generated by \`npm run art:spec\`. Do not edit by hand; change \`src/artslots.ts\` and run it again.

**Progress: ${have} of ${slots.length} pictures delivered.** The game draws its own stand-in for every picture that is missing, so nothing is blocked while the art is made.

---

## 1. The game

*Needle in a Haystack* is a cozy hidden-object game. The player brushes the straw of a haystack aside to find a small needle, and finds little collectable objects (buttons, thimbles, keys, acorns...) hidden in it. There is no timer, no score and no way to lose. It is set on a warm, old-fashioned American farm across five places: the Meadow, the Barnyard, the Orchard, the Snowy Farm and a Starry Night.

**Who plays it:** mostly adults over 55 in the United States. This decides a lot:

- Shapes must be **big, clear and easy to read**, with good contrast. Clarity matters more than fine detail.
- The mood is **warm, nostalgic and calm**. Nothing scary, sharp, dark or noisy.
- Everything is shown on screens of all sizes, from a phone to a large monitor, so pictures must stay readable when small.

## 2. What we need from you

| Kind | How many | Format | Where it is used |
|---|---|---|---|
| Items | ${count('items') - slots.filter(s => s.kind === 'decoy').length} collectable objects | PNG, ${I.master} x ${I.master} | Hidden in the hay, then in the collection book, the shop and the "well done" card |
| Look-alikes | ${slots.filter(s => s.kind === 'decoy').length} (a pin and a nail) | PNG, ${I.master} x ${I.master} | Hidden in the hay to look like the needle |
| Icons | ${count('icons')} | PNG ${IC.scale * 64} x ${IC.scale * 64} **or** SVG | Buttons, rewards and the shop |
| Scenery props | ${count('props')} | PNG or SVG, sizes below | Decorations in the margins of the level map and behind the board |

The full list, with the exact file name and size of each picture, is at the end of this document (and in \`art-slots.csv\`).

## 3. The look

These rules come from the pictures the game already has. The \`reference/\` folder has every current picture: **match its size and proportions, but redraw it in your own style**. Please do not trace it.

**All pictures**
- Soft, rounded, friendly shapes. Slightly pastel, warm colours. One small highlight is enough.
- Light comes from the **top left**.
- No pure black: use a dark warm brown (about #3a2a1a) for darks.
- No photo textures, no text, no lettering.

**Items and look-alikes**
- A thin, warm dark-brown outline (about **#76502b**, around ${Math.round((I.master / 64) * 3)} px thick at ${I.master} px).
- The hay is golden-yellow and tan, so an object must **stand out from straw**. Avoid golden-yellow and tan as the main colour. Clean, strong colours work best (red, teal, blue, green, pink, silver).
- It must be recognisable as a **silhouette at 48 x 48 px**, because that is about how big it is in the hay.

**Icons**
- A single clear object on a transparent background. They are shown small (24 to 64 px) on buttons, so keep the shape simple and bold.
- All 13 icons must look like one family: the same outline weight, the same level of detail, the same light.

**Scenery props**
- Flat shapes with a little shading, in the soft colours of each world. Most have **no outline**; a thin soft edge is fine where it helps (the butterfly and the fence have one).
- A soft ground shadow under the object (a flat ellipse, about 20% opacity) is welcome, because props stand on the ground.
- They are shown behind the game, so they should be calm and not draw the eye away from the haystack.

## 4. Technical rules

**Files**
- Name: exactly the file name in the list, **lower case**, with \`.png\` or \`.svg\` (for example \`items/button.png\`).
- One object per file. Transparent background. No frame, no text.
- At most **${kb} KB** per file.
- Deliver **either** a PNG **or** an SVG for a picture, never both.

**PNG**
- 8-bit RGBA, sRGB, **not interlaced**, with a real transparent background (not a white or checkerboard one).
- The exact size in the list (items ${I.master} x ${I.master}; icons ${IC.scale * 64} x ${IC.scale * 64}; props ${PR.scale} times their viewBox).
- Leave empty space around the object: at least **${I.margin} px for items**, ${IC.margin} px for icons and ${PR.margin} px for props.
- Items: the longest side of the object takes **${pct(I.fill[0])}% to ${pct(I.fill[1])}%** of the file. Icons: ${pct(IC.fill[0])}% to ${pct(IC.fill[1])}%.
- **No drop shadow or ground shadow on items and icons.** The game adds a soft shadow itself.
- Items are drawn the natural way up. The game turns them by a random angle when it hides them in the hay. The look-alikes (pin, nail) are drawn lying flat, with the head on the right.

**SVG** (icons and props only)
- A \`viewBox\` with the same proportions as the list says (for icons \`0 0 64 64\`).
- Plain shapes, paths and simple gradients only. **Convert text to outlines.** No scripts, no external links, no embedded fonts, no \`foreignObject\`.
- Avoid blur, filters and masks: they draw slowly and look different in different browsers.
- No background rectangle: the background must be transparent.

## 5. How to deliver

1. Put the files in folders named after the kind, keeping the names from the list:

\`\`\`
incoming/
  items/    button.png  spool.png  ...
  icons/    detector.svg  cells.png  ...
  props/    windmill.svg  barn.png  ...
\`\`\`

2. Send the \`incoming\` folder (a zip is fine) to the developer. The developer runs a checker that tests every file and replies with exactly what to fix, in plain words (wrong size, background not transparent, object too close to the edge, wrong file name...). Files with a problem are never used by the game.
3. To change a picture later, deliver it again **with the same file name**. File names never change.

**What is delivered together**
- **Icons:** all ${count('icons')} in one batch, so the buttons never mix two styles.
- **Scenery props:** one world at a time (all the pictures of a world together).
- **Items:** in any order and in any quantity; each one is used as soon as it arrives. It is best to deliver a whole set (for example "The Sewing Box") at a time so the collection book looks consistent.

## 6. Checklist before delivering

- [ ] The file name matches the list exactly (lower case).
- [ ] The size is exactly the one in the list (PNG), or the viewBox has the right proportions (SVG).
- [ ] The background is really transparent (open the file on a coloured background to check).
- [ ] There is empty space on every side, and nothing is cut off.
- [ ] There is no text, no frame, no background and (for items and icons) no shadow.
- [ ] Items: still recognisable when shrunk to 48 x 48 px, and clearly different from golden straw.
- [ ] Every picture in a kit looks like it belongs with the others.
- [ ] The file is under ${kb} KB.

## 7. The list

${sections}
`;

const q = v => `"${String(v).replace(/"/g, '""')}"`;
const csv = ['path,id,kind,name,kit,formats,width,height,viewbox,status', ...slots.map(s => [`${s.folder}/${s.id}`, s.id, s.kind, s.name, s.kit, s.formats.join('/'), s.w, s.h, `${s.box[0]}x${s.box[1]}`, isDone(s) ? 'delivered' : 'missing'].map(q).join(','))].join('\n') + '\n';

fs.mkdirSync(path.dirname(DIRS.brief), { recursive: true });
fs.writeFileSync(DIRS.brief, md);
fs.writeFileSync(DIRS.csv, csv);
console.log(`Wrote ${path.relative(process.cwd(), DIRS.brief)} and ${path.relative(process.cwd(), DIRS.csv)}: ${slots.length} pictures, ${have} delivered.`);
