// Writes the sheet to hand to the art team. Run: npm run art:spec
//   art/ART_SPEC.md      the rules and the list of every picture, with what is done and what is missing
//   art/art-slots.csv    the same list as a table (for a spreadsheet)
import fs from 'node:fs';
import path from 'node:path';
import { DIRS, loadSlots } from './art-lib.mjs';

const { spec, slots } = await loadSlots();
let delivered = {};
try { delivered = JSON.parse(fs.readFileSync(DIRS.manifest, 'utf8')).items ?? {}; } catch { /* no manifest yet */ }
const status = s => (delivered[s.id] ? 'delivered' : 'missing');
const M = spec.master;
const pct = n => Math.round(n * 100);

const groups = [];
for (const s of slots) {
  let g = groups.find(x => x.name === s.group);
  if (!g) groups.push((g = { name: s.group, slots: [] }));
  g.slots.push(s);
}
const have = slots.filter(s => delivered[s.id]).length;

const md = `# Needle in a Haystack: art specification

Generated by \`npm run art:spec\`. Do not edit by hand; change \`src/artslots.ts\` and run it again.

**Progress: ${have} of ${slots.length} pictures delivered.** The game draws its own stand-in for every picture that is missing, so nothing is blocked while the art is made.

## What to deliver

| | |
|---|---|
| File | PNG, **${M} x ${M} px**, RGBA (8 bit), **transparent background**, not interlaced, sRGB |
| Name | Exactly the file name in the list below, lower case (for example \`button.png\`) |
| Size | At most ${spec.maxBytes / 1000} KB per file. Run it through a PNG optimiser if needed |
| Space | At least **${spec.margin} px of empty space** on every side of the object |
| Object size | The longest side of the object takes **${pct(spec.fill[0])}% to ${pct(spec.fill[1])}%** of the file |
| Position | Centred. One object per file, no background, no frame, no text |
| Shadow | **None.** Do not paint a drop shadow or a ground shadow. The game adds a soft one |
| Orientation | Drawn the natural way up. The game turns each object by a random angle when it hides it in the hay |

## How the pictures are used

- **In the haystack:** about 46 px wide on a normal screen (it gets bigger when the player zooms in), partly covered by straw, and turned at random angles. The shape must be easy to read when small, so check it at 48 x 48 px.
- **In the collection book, the shop, and the "well done" card:** shown larger, about 80 to 120 px.
- **Hay is golden:** objects must stand out from straw. Avoid golden-yellow and tan as the main colour. Strong, clean colours and a clear outline work best.

## Style

Soft, rounded, friendly shapes with a thin warm dark-brown outline (about the colour #76502b, around ${Math.round((M / 64) * 3)} px thick at ${M} px). Bright, slightly pastel colours with one small highlight. No harsh black, no photo textures, nothing scary. The audience is mostly adults over 55, so clear shapes and good contrast matter more than fine detail.

## Delivering

1. Put the files in \`games/needle-game/art/incoming/\`.
2. Run \`npm run art:check\`. It tells you exactly what to fix (wrong size, no transparency, object too close to the edge, wrong name...).
3. When it shows no errors, the developer runs \`npm run art:sync\`, which puts the files into the game.

Files with errors are never used by the game.

## The list

${groups
  .map(g => `### ${g.name}\n\n| File | Name | Rarity | Status |\n|---|---|---|---|\n${g.slots.map(s => `| \`${s.id}.png\` | ${s.name} | ${s.rarity ?? '-'} | ${status(s)} |`).join('\n')}\n`)
  .join('\n')}`;

const csv = ['file,id,kind,name,group,rarity,status,size_px', ...slots.map(s => [`${s.id}.png`, s.id, s.kind, s.name, s.group, s.rarity ?? '', status(s), `${M}x${M}`].map(v => `"${String(v).replace(/"/g, '""')}"`).join(','))].join('\n') + '\n';

fs.mkdirSync(path.dirname(DIRS.sheet), { recursive: true });
fs.writeFileSync(DIRS.sheet, md);
fs.writeFileSync(DIRS.csv, csv);
console.log(`Wrote ${path.relative(process.cwd(), DIRS.sheet)} and ${path.relative(process.cwd(), DIRS.csv)}: ${slots.length} pictures, ${have} delivered.`);
